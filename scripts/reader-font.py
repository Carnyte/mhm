#!/usr/bin/env python3
"""Writes src/reader/literata.ts: Literata (assets/fonts, SIL OFL 1.1) as small WOFF2 subsets in
base64, for the reader page's @font-face rules. The reader page is a WebView document with the
site's (or about:blank's) origin, so it can't load the app's font files; a data: URI works
everywhere, offline too. Latin, Greek and Cyrillic only: other scripts fall back to Georgia.

Usage (needs `pip install fonttools brotli`; run from the repo root, then commit the result):
    python3 scripts/reader-font.py
"""

import base64
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

UNICODES = (
    "U+0000-024F,U+0259,U+02B0-02FF,U+0300-036F,U+0370-03FF,U+0400-04FF,U+1E00-1EFF,"
    "U+2000-206F,U+20A0-20CF,U+2100-214F,U+2190-2199,U+2212,U+2215,U+FB00-FB06,U+FEFF,U+FFFD"
)
FACES = [("regular", "Literata-Regular.ttf"), ("italic", "Literata-Italic.ttf"), ("bold", "Literata-Bold.ttf")]


def woff2(path: str) -> bytes:
    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.flavor = "woff2"
    opts.name_IDs = ["*"]  # keeps the copyright and licence names (OFL)
    font = TTFont(path)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=subset.parse_unicodes(UNICODES))
    sub.subset(font)
    out = io.BytesIO()
    font.flavor = "woff2"
    font.save(out)
    return out.getvalue()


def main() -> None:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    lines = [
        "// Generated by scripts/reader-font.py from assets/fonts (Literata, SIL Open Font License 1.1,",
        "// assets/fonts/OFL.txt). Do not edit by hand. WOFF2 subsets (Latin, Greek, Cyrillic) in base64.",
        "",
    ]
    for name, file in FACES:
        data = base64.b64encode(woff2(os.path.join(root, "assets", "fonts", file))).decode("ascii")
        lines.append(f"export const LITERATA_{name.upper()} =\n  '{data}';")
        lines.append("")
    target = os.path.join(root, "src", "reader", "literata.ts")
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {target} ({os.path.getsize(target) // 1024} KB)", file=sys.stderr)


if __name__ == "__main__":
    main()
